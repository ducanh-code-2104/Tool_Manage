private void loadToolData() {

    javax.swing.table.DefaultTableModel model =
        new javax.swing.table.DefaultTableModel(
            new Object[]{
                "Tool Name",
                "Part Number",
                "Serial Number",
                "Status"
            }, 0
        );

    String sql = """
        SELECT
            t.tool_name,
            p.part_number,
            s.serial_number,
            s.status
        FROM tools t
        JOIN part_numbers p
            ON t.tool_id = p.tool_id
        JOIN serial_numbers s
            ON p.part_id = s.part_id
        ORDER BY t.tool_name, p.part_number
        """;

    try (
        java.sql.Connection conn =
            DatabaseConnection.getConnection();

        java.sql.PreparedStatement stmt =
            conn.prepareStatement(sql);

        java.sql.ResultSet rs =
            stmt.executeQuery()
    ) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getString("tool_name"),
                rs.getString("part_number"),
                rs.getString("serial_number"),
                rs.getString("status")
            });
        }

        tblTools.setModel(model);

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Loi tai du lieu: " + e.getMessage()
        );
    }
        
}private void saveNewTool(
        String toolName,
        String partNumber,
        String serialNumber,
        String status) throws java.sql.SQLException {

    try (java.sql.Connection conn =
            DatabaseConnection.getConnection()) {

        conn.setAutoCommit(false);

        try {
            int toolId;
            int partId;

            // Find existing Tool Name
            String findTool =
                    "SELECT tool_id FROM tools WHERE tool_name = ?";

            try (java.sql.PreparedStatement ps =
                    conn.prepareStatement(findTool)) {

                ps.setString(1, toolName);

                try (java.sql.ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        toolId = rs.getInt("tool_id");
                    } else {
                        toolId = -1;
                    }
                }
            }

            // Insert Tool Name if not found
            if (toolId == -1) {
                String insertTool =
                        "INSERT INTO tools (tool_name) VALUES (?)";

                try (java.sql.PreparedStatement ps =
                        conn.prepareStatement(
                                insertTool,
                                java.sql.Statement.RETURN_GENERATED_KEYS)) {

                    ps.setString(1, toolName);
                    ps.executeUpdate();

                    try (java.sql.ResultSet keys =
                            ps.getGeneratedKeys()) {
                        if (!keys.next()) {
                            throw new java.sql.SQLException(
                                    "Cannot get new tool ID");
                        }
                        toolId = keys.getInt(1);
                    }
                }
            }

            // Find existing Part Number for this tool
            String findPart =
                    "SELECT part_id FROM part_numbers " +
                    "WHERE tool_id = ? AND part_number = ?";

            try (java.sql.PreparedStatement ps =
                    conn.prepareStatement(findPart)) {

                ps.setInt(1, toolId);
                ps.setString(2, partNumber);

                try (java.sql.ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        partId = rs.getInt("part_id");
                    } else {
                        partId = -1;
                    }
                }
            }

            // Insert Part Number if not found
            if (partId == -1) {
                String insertPart =
                        "INSERT INTO part_numbers " +
                        "(tool_id, part_number) VALUES (?, ?)";

                try (java.sql.PreparedStatement ps =
                        conn.prepareStatement(
                                insertPart,
                                java.sql.Statement.RETURN_GENERATED_KEYS)) {

                    ps.setInt(1, toolId);
                    ps.setString(2, partNumber);
                    ps.executeUpdate();

                    try (java.sql.ResultSet keys =
                            ps.getGeneratedKeys()) {
                        if (!keys.next()) {
                            throw new java.sql.SQLException(
                                    "Cannot get new part ID");
                        }
                        partId = keys.getInt(1);
                    }
                }
            }

            // Insert physical tool Serial Number
            String insertSerial =
                    "INSERT INTO serial_numbers " +
                    "(part_id, serial_number, status) " +
                    "VALUES (?, ?, ?)";

            try (java.sql.PreparedStatement ps =
                    conn.prepareStatement(insertSerial)) {

                ps.setInt(1, partId);
                ps.setString(2, serialNumber);
                ps.setString(3, status);
                ps.executeUpdate();
            }

            conn.commit();

        } catch (java.sql.SQLException e) {
            conn.rollback();
            throw e;
        }
    }
}
